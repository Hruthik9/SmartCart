// Helper maps for instant barcode & query lookups
export const PRODUCT_BY_BARCODE: Record<string, Product> = {};
export const PRODUCT_BY_ID: Record<string, Product> = {};

GROCERY_CATALOG.forEach(product => {
  PRODUCT_BY_BARCODE[product.barcode] = product;
  PRODUCT_BY_ID[product.id] = product;
});

export function findProductByBarcode(barcode: string): Product | undefined {
  return PRODUCT_BY_BARCODE[barcode.trim()];
}

export function searchCatalog(query: string): Product[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return GROCERY_CATALOG.filter(p => 
    p.name.toLowerCase().includes(q) ||
    p.brand.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.badges.some(b => b.toLowerCase().includes(q))
  );
}
